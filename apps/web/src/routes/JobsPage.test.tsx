it("saves channels through the matching job API, retains a channel, and keeps failed saves visibly unchanged", async () => {
  let builtinChannels = ['web_log'];
  let customChannels = ['web_log'];
  vi.mocked(api.fetchJobs).mockImplementation(async () => [{ id: 'premarket', name: '盘前扫描', cadence: 'trading_day 08:50', enabled: true, delivery_channels: builtinChannels }]);
  vi.mocked(api.fetchCustomJobs).mockImplementation(async () => [{ id: 'custom-1', name: '自建观察', prompt: '观察市场', schedule: 'trading_day 10:30', enabled: true, delivery_channels: customChannels, trading_day_only: true, created_by: 'user', created_at: null }]);
  vi.mocked(api.fetchJobRuns).mockResolvedValue([]);
  vi.mocked(api.fetchSchedulerConfig).mockResolvedValue({ enabled: false, timezone: 'Asia/Shanghai', premarket_time: '08:50', morning_plan_time: '09:15', close_time: '15:10', eod_review_time: '15:30', postmarket_time: '16:30', weekly_day: 'sat', weekly_time: '10:00' });
  vi.mocked(api.updateBuiltinJob).mockImplementation(async (id, patch) => { builtinChannels = patch.delivery_channels; return { id, delivery_channels: builtinChannels }; });
  vi.mocked(api.updateCustomJob).mockImplementation(async (id, patch) => { customChannels = patch.delivery_channels!; return { id, name: '自建观察', enabled: true, delivery_channels: customChannels }; });
  view = document.createElement('div'); document.body.append(view); root = createRoot(view);
  client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  await act(async () => root.render(<QueryClientProvider client={client}><JobsPage /></QueryClientProvider>)); await settle();
  const option = (label: string) => [...document.querySelectorAll<HTMLLabelElement>('.delivery-option')].find(el => el.textContent === label)!.querySelector<HTMLInputElement>('input')!;
  const change = async (label: string) => { await act(async () => option(label).click()); await settle(); };
  await click('[aria-label="调整 盘前扫描 的推送渠道"]');
  await change('Web 通知');
  expect(document.querySelector('.delivery-error')?.textContent).toBe('至少保留一个推送渠道');
  expect(api.updateBuiltinJob).not.toHaveBeenCalled();
  let finishSave!: () => void;
  vi.mocked(api.updateBuiltinJob).mockImplementationOnce(async (id, patch) => {
    await new Promise<void>(resolve => { finishSave = resolve; });
    builtinChannels = patch.delivery_channels;
    return { id, delivery_channels: builtinChannels };
  });
  await change('飞书');
  expect(option('企业微信').matches(':disabled')).toBe(true);
  expect(document.querySelector('.delivery-popover [role="status"]')?.textContent).toBe('正在保存…');
  await change('企业微信');
  expect(api.updateBuiltinJob).toHaveBeenCalledTimes(1);
  await act(async () => finishSave()); await settle();
  expect(api.updateBuiltinJob).toHaveBeenLastCalledWith('premarket', { delivery_channels: ['web_log', 'feishu'] });
  expect(option('飞书').checked).toBe(true);
  expect(document.querySelector('.delivery-popover [role="status"]')?.textContent).toBe('已保存');
  vi.mocked(api.updateBuiltinJob).mockRejectedValueOnce(new Error('保存失败，请重试'));
  await change('飞书');
  expect(option('飞书').checked).toBe(true);
  expect(document.querySelector('.delivery-error')?.textContent).toBe('保存失败，请重试');
  await act(async () => document.querySelector<HTMLButtonElement>('[aria-label="关闭渠道设置"]')!.click()); await settle();
  await click('[aria-label="调整 自建观察 的推送渠道"]');
  await change('企业微信');
  expect(api.updateCustomJob).toHaveBeenLastCalledWith('custom-1', { delivery_channels: ['web_log', 'wecom'] });
  expect(option('企业微信').checked).toBe(true);
  expect(api.runJob).not.toHaveBeenCalled();
  expect(api.runCustomJob).not.toHaveBeenCalled();
});

