import { act } from "react";
import { createRoot, type Root } from "react-dom/client";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { afterEach, expect, it, vi } from "vitest";
import { JobsPage } from "./JobsPage";
import * as api from "@/lib/workbench-api";
vi.mock("@/lib/workbench-api", () => ({ createCustomJob: vi.fn(), deleteCustomJob: vi.fn(), fetchCustomJobs: vi.fn(), fetchJobRunDetail: vi.fn(), fetchJobRuns: vi.fn(), fetchJobs: vi.fn(), fetchSchedulerConfig: vi.fn(), runCustomJob: vi.fn(), runJob: vi.fn(), updateBuiltinJob: vi.fn(), updateCustomJob: vi.fn(), updateSchedulerConfig: vi.fn() }));
